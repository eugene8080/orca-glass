// Run on a fresh isolated Hermes fixture preview. Never touches a real bridge.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const sim = `http://127.0.0.1:${process.env.ORCA_GLASS_SIMULATOR_PORT || 9902}`;
const fixture = `http://127.0.0.1:${process.env.ORCA_GLASS_SIM_PORT || 8795}`;
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const json = async url => { const r = await fetch(url); assert.ok(r.ok); return r.json(); };
const input = async action => {
  const r = await fetch(`${sim}/api/input`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ action }) });
  assert.ok(r.ok); await wait(350);
};
let since = 0;
const calls = async () => (await json(`${sim}/api/console`)).entries.filter(e => e.id > since && e.message.startsWith('Native call ')).map(e => JSON.parse(e.message.slice(12)));
const page = async () => (await calls()).filter(c => c.method === 'rebuildPageContainer').at(-1).data;
await mkdir('.local/hermes-preview', { recursive: true });
const snap = async name => {
  const r = await fetch(`${sim}/api/screenshot/glasses`); assert.ok(r.ok);
  await writeFile(`.local/hermes-preview/${name}.png`, Buffer.from(await r.arrayBuffer()));
};
const initial = await json(`${fixture}/__fixture`);
assert.equal(initial.threads.filter(t => t.agent === 'hermes').length, 7);
assert.equal(initial.threads.length, 9);
since = Math.max(0, ...(await json(`${sim}/api/console`)).entries.map(e => e.id));
await input('click');
let view = await page();
const filter = view.listObject[0].itemContainer.itemName;
assert.deepEqual(filter.map(s => s.replace(' ✓', '')), ['<-', 'All Sessions', 'Claude', 'Codex', 'Hermes']);
await snap('agent-filter');
for (let i = 0; i < 4; i++) await input('down');
await input('click');
view = await page();
const body = view.textObject.find(c => c.containerName === 'body').content;
assert.equal(body.split('\n').length, 9);
assert.ok(!body.includes('regression row'));
assert.equal((view.textObject.find(c => c.containerName === 'menu-right').content.match(/\/Hermes\]/g) || []).length, 7);
await snap('seven-hermes-sessions');
await input('down'); await input('down'); await input('click'); await wait(900);
assert.ok(JSON.stringify(await calls()).includes('This is a Hermes conversation using GPT synthetic'));
await snap('reader');
await input('long_press'); await wait(250); await input('long_press_release'); await wait(600);
assert.equal((await json(`${fixture}/__fixture`)).sends.length, initial.sends.length);
await snap('review-before-confirm');
await input('click'); await wait(1000);
const after = await json(`${fixture}/__fixture`);
assert.equal(after.sends.length, initial.sends.length + 1);
assert.equal(after.sends.at(-1).handle, initial.threads.find(t => t.agent === 'hermes').handle);
assert.equal(after.sends.at(-1).text, initial.transcript);
assert.ok(JSON.stringify(await calls()).includes('Synthetic reply accepted for this exact Hermes profile/session.'));
await snap('confirmed-synthetic-reply');
await input('double_click');
await snap('left-open-hermes-filter');
await writeFile('.local/hermes-preview/native-calls.json', JSON.stringify(await calls(), null, 2));
console.log('Native Hermes preview passed: one Hermes filter, seven mixed-model sessions, saved reading, no send before confirmation, one exact synthetic reply. Preview left open.');
