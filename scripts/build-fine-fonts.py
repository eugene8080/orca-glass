"""Build the small-text reader fonts from their upstream releases (run by hand).

Inputs (downloaded release archives, unpacked):
  --spleen  spleen-2.2.0/spleen-6x12.bdf   (BSD-2-Clause, Frederic Cambus)
  --mono    JetBrainsMono-2.304 fonts/ttf/JetBrainsMono-Regular.ttf  (OFL-1.1, JetBrains)
Outputs:
  app/src/fonts/spleen-6x12.ts          every BDF glyph as 12 rows of 6-bit masks
  app/src/fonts/jetbrains-mono.woff     Latin, punctuation, arrows, box drawing, shapes

The glyph table lets the reader draw Spleen pixel-exact without a canvas font
(canvas anti-aliasing would blur a 6x12 bitmap font on the G2's 4-bit display).
"""
from __future__ import annotations

import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def spleen_table(bdf: Path) -> str:
    lines = bdf.read_text(encoding="ascii").splitlines()
    box = next(l for l in lines if l.startswith("FONTBOUNDINGBOX")).split()
    cell_w, cell_h, _, base_y = (int(v) for v in box[1:])
    if (cell_w, cell_h) != (6, 12):
        raise SystemExit(f"expected a 6x12 font, got {cell_w}x{cell_h}")
    glyphs: list[str] = []
    i = 0
    while i < len(lines):
        if not lines[i].startswith("STARTCHAR"):
            i += 1
            continue
        code = w = h = xoff = yoff = None
        rows: list[int] = []
        i += 1
        while not lines[i].startswith("ENDCHAR"):
            parts = lines[i].split()
            if parts[0] == "ENCODING":
                code = int(parts[1])
            elif parts[0] == "BBX":
                w, h, xoff, yoff = (int(v) for v in parts[1:5])
            elif parts[0] == "BITMAP":
                i += 1
                while not lines[i].startswith("ENDCHAR"):
                    rows.append(int(lines[i], 16))
                    i += 1
                break
            i += 1
        if code is None or code < 32 or code > 0xFFFF or w is None:
            continue
        # Place the glyph's own box inside the 6x12 cell. BDF rows are MSB-first,
        # padded to whole bytes; keep the leftmost `w` bits shifted by xoff.
        cell = [0] * cell_h
        top = (cell_h + base_y) - (yoff + h)  # cell row of the glyph's first bitmap row
        byte_bits = ((w + 7) // 8) * 8
        for r, value in enumerate(rows):
            y = top + r
            if 0 <= y < cell_h:
                bits = value >> (byte_bits - w)
                cell[y] = (bits << max(0, cell_w - w - xoff)) & 0x3F
        glyphs.append(f"{code:x}:" + "".join(f"{v:02x}" for v in cell))
    body = ";".join(glyphs)
    return (
        "// Generated by scripts/build-fine-fonts.py from Spleen 6x12 2.2.0.\n"
        "// Copyright (c) 2018-2026, Frederic Cambus. BSD-2-Clause; see app/src/fonts/SPLEEN-LICENSE.txt.\n"
        "// Each entry: hex code point ':' then 12 rows, 2 hex digits each (6-bit masks, bit 5 = left).\n"
        f"export const SPLEEN_6X12 = '{body}';\n"
    )


def mono_subset(ttf: Path, out: Path) -> None:
    from fontTools import subset
    options = subset.Options()
    options.flavor = "woff"  # zlib; brotli (woff2) is not installed here
    options.layout_features = ["kern"]  # no ligatures: one glyph per character cell
    options.name_IDs = ["*"]
    font = subset.load_font(str(ttf), options)
    s = subset.Subsetter(options)
    s.populate(unicodes=[*range(0x20, 0x7F), *range(0xA0, 0x180), *range(0x2010, 0x2070),
                         *range(0x2190, 0x2200), *range(0x2500, 0x25A0), *range(0x25A0, 0x2600),
                         0x2713, 0x2714, 0x2717, 0x2718, 0x276F, 0x23F5, 0x23FA, 0x2022, 0x2026])
    s.subset(font)
    subset.save_font(font, str(out), options)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spleen", type=Path, required=True)
    ap.add_argument("--mono", type=Path, required=True)
    args = ap.parse_args()
    fonts = REPO / "app" / "src" / "fonts"
    fonts.mkdir(exist_ok=True)
    (fonts / "spleen-6x12.ts").write_text(spleen_table(args.spleen), encoding="utf-8")
    mono_subset(args.mono, fonts / "jetbrains-mono.woff")
    print("ok", (fonts / "spleen-6x12.ts").stat().st_size, (fonts / "jetbrains-mono.woff").stat().st_size)


if __name__ == "__main__":
    main()
